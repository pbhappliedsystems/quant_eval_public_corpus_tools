"""Rebuild the inputs make_figures.py reads, from the published D5 and D7.

make_figures.py reads exactly these rollup.json fields and nothing else:

    paired_runner_comparison.<family>.pass_rate_delta_runner_b_minus_runner_a
    paired_runner_comparison.<family>.pass_rate_delta_ci.{low,high}
    paired_runner_comparison.<family>.mcnemar_exact.p_value
    efficiency.artifact_footprint[0].{baseline_bytes,quantized_bytes,
                                      compression_ratio,size_reduction_fraction}
    efficiency.runtime_comparison.headline_runtime_metric.{value,direction}

build_datasets.py copies each of them into D5 or D7 unchanged, so a reader can
write a reduced rollup.json per run from the datasets and run make_figures.py
without the source bundles. The reduced file carries no other field.
"""
import json
import os

from .constants import FAMILIES


def _num(s):
    s = str(s).strip()
    if s == "":
        return None
    try:
        return int(s)
    except ValueError:
        return float(s)


def build_reduced_rollups(corpus):
    """{run_id: reduced rollup dict} from D5 and D7."""
    d5, d7 = corpus.d5(), corpus.d7()
    runs = {}
    for r in d5:
        o = runs.setdefault(r["run_id"], {"run_id": r["run_id"],
                                          "paired_runner_comparison": {}})
        o["paired_runner_comparison"][r["family"]] = {
            "pass_rate_delta_runner_b_minus_runner_a":
                _num(r["pass_rate_delta_runner_b_minus_runner_a"]),
            "pass_rate_delta_ci": {"low": _num(r["delta_ci_low"]),
                                   "high": _num(r["delta_ci_high"])},
            "mcnemar_exact": {"p_value": _num(r["mcnemar_p_value"])},
        }
    for r in d7:
        o = runs.setdefault(r["run_id"], {"run_id": r["run_id"],
                                          "paired_runner_comparison": {}})
        o["efficiency"] = {
            "artifact_footprint": [{
                "baseline_bytes": _num(r["baseline_bytes"]),
                "quantized_bytes": _num(r["quantized_bytes"]),
                "compression_ratio": _num(r["compression_ratio"]),
                "size_reduction_fraction": _num(r["size_reduction_fraction"]),
            }],
            "runtime_comparison": {"headline_runtime_metric": {
                "value": _num(r["observed_wall_time_ratio"]),
                "direction": r["wall_time_direction"] or None,
            }},
        }
    for rid, o in runs.items():
        missing = [f for f in FAMILIES if f not in o["paired_runner_comparison"]]
        if missing or "efficiency" not in o:
            raise ValueError("run %s lacks %s" % (rid, ", ".join(
                missing + ([] if "efficiency" in o else ["D7 row"]))))
    return runs


def write_figure_inputs(corpus, out_dir):
    """Write <out>/<run_id>/publication/rollup.json for every run, plus
    <out>/corpus_runs.txt and <out>/hardware_map.txt (accelerators from D7
    v1.0.1). Returns the list of files written."""
    runs = build_reduced_rollups(corpus)
    written = []
    for rid, o in sorted(runs.items()):
        d = os.path.join(out_dir, rid, "publication")
        os.makedirs(d, exist_ok=True)
        p = os.path.join(d, "rollup.json")
        with open(p, "w", encoding="utf-8") as f:
            json.dump(o, f, indent=2)
        written.append(p)
    p = os.path.join(out_dir, "corpus_runs.txt")
    with open(p, "w", encoding="utf-8") as f:
        f.write("# Generated by qe-corpus figure-inputs from D5 and D7.\n")
        for rid in sorted(runs):
            f.write(rid + "\n")
    written.append(p)
    rows = corpus.d7()
    if all(r.get("baseline_accelerator") and r.get("quantized_accelerator") for r in rows):
        p = os.path.join(out_dir, "hardware_map.txt")
        with open(p, "w", encoding="utf-8") as f:
            f.write("# Generated by qe-corpus figure-inputs from D7 "
                    "baseline_accelerator / quantized_accelerator.\n")
            for r in sorted(rows, key=lambda r: r["run_id"]):
                f.write("%s  %s  %s\n" % (r["run_id"], r["baseline_accelerator"],
                                          r["quantized_accelerator"]))
        written.append(p)
    return written
